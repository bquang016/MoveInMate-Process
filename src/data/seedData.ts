interface RawDayTaskInput {
  id: string;
  ownerCode: MemberCode;
  reviewerCode: MemberCode;
  supporterCodes: MemberCode[];
  handoverToCodes: MemberCode[];
  dayNumber: number;
  dayTheme: string;
  moduleSlice: ModuleSlice;
  title: string;
  description: string;
  deliverableSummary: string;
  handoverCondition: string;
  priority: TaskPriority;
  deadlineDayOffset: number;
  criteriaLabels: Array<{
    label: string;
    category: CriterionCategory;
    isMandatory?: boolean;
  }>;
  dependsOnTaskId?: string;
  dependencyNote?: string;
}

function buildDailyTask(raw: RawDayTaskInput): TrackerTask {
  const deadlineDate = new Date(
    Date.UTC(2026, 10, 14 + raw.deadlineDayOffset, 17, 0, 0),
  );
  return {
    id: raw.id,
    workspaceId: DEFAULT_WORKSPACE_ID,
    dayNumber: raw.dayNumber,
    dayPhase: `Ngày ${raw.dayNumber} · ${raw.dayTheme}`,
    moduleSlice: raw.moduleSlice,
    title: raw.title,
    description: raw.description,
    deliverableSummary: raw.deliverableSummary,
    ownerCode: raw.ownerCode,
    reviewerCode: raw.reviewerCode,
    supporterCodes: raw.supporterCodes,
    handoverToCodes: raw.handoverToCodes,
    handoverCondition: raw.handoverCondition,
    status: 'todo',
    priority: raw.priority,
    deadline: deadlineDate.toISOString(),
    blocker: '',
    isBlocked: false,
    reviewerApproved: false,
    reviewerApprovedBy: null,
    reviewerApprovedAt: null,
    reviewerNote: '',
    aiSuggestion: `Có thể bắt đầu thực hiện ngay (kể cả làm vượt tiến độ trước Ngày ${raw.dayNumber}). Sau khi tick đủ các tiêu chí bắt buộc, hãy chuyển sang Review để ${raw.reviewerCode} kiểm duyệt.`,
    aiConfidence: 'high',
    evidenceLinks: [],
    notes: '',
    updatedAt: '2026-11-14T03:00:00Z',
    criteria: raw.criteriaLabels.map((item, idx) => ({
      id: `C-${raw.id}-${idx + 1}`,
      taskId: raw.id,
      label: item.label,
      category: item.category,
      isMandatory: item.isMandatory ?? true,
      isCompleted: false,
      completedBy: null,
      completedAt: null,
      sortOrder: idx + 1,
    })),
    dependencies: raw.dependsOnTaskId
      ? [
          {
            id: `dep-${raw.id}`,
            taskId: raw.id,
            dependsOnTaskId: raw.dependsOnTaskId,
            dependencyType: 'contract',
            note:
              raw.dependencyNote ||
              `Kế thừa đầu ra từ ${raw.dependsOnTaskId} (vẫn có thể chủ động làm vượt tiến độ ngay).`,
          },
        ]
      : [],
  };
}

